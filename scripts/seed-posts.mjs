let token = null, lastAt = 0, sent = 0;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function call(method, path, { as, admin, date = TODAY, time = '10:00', body, ok = [] } = {}) {
  const wait = lastAt + MIN_GAP_MS - Date.now();
  if (wait > 0) await sleep(wait);
  lastAt = Date.now(); sent++;
  const headers = { 'content-type': 'application/json', 'X-Sim-Date': date, 'X-Sim-Time': time };
  if (token) headers['X-Sim-Token'] = token;
  if (admin) headers['X-Role'] = 'admin';
  else if (as) { headers['X-Role'] = 'member'; headers['X-User-Id'] = as; }
  let res;
  for (let a = 0; ; a++) {
    try {
      res = await fetch(API + path, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
      if (res.status >= 500 && a < 2) { await sleep(1000); continue; }
      break;
    } catch (e) { if (a >= 2) throw e; await sleep(1000); }
  }
  const text = await res.text();
  const data = text ? JSON.parse(text) : null;
  if (res.status >= 400 && !ok.includes(res.status)) throw new Error(`${method} ${path} → ${res.status} ${data?.error?.code ?? ''} ${data?.error?.message ?? text}`);
  return data;
}

