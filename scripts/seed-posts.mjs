const TIER = { hot: { v: 14, c: 8, l: 6 }, mid: { v: 7, c: 4, l: 3 }, low: { v: 2, c: 2, l: 1 } };

async function main() {
  console.log(`대상 Worker: ${API}`);
  token = (await call('POST', '/api/enter', { body: { passcode: PASSCODE } })).token;
  const groups = (await call('GET', '/api/groups', { admin: true })).items;
  const stats = { posts: 0, skipped: 0, comments: 0, likes: 0, views: 0 };
  let n = 0;
  for (const g of groups) {
    const list = G[g.name];
    if (!list) continue;
    const mem = (await call('GET', `/api/groups/${g.id}/members`, { admin: true })).items.filter((m) => m.role !== 'pending');
    const staff = mem.filter((m) => m.role === 'owner' || m.role === 'staff');
    const plain = mem.filter((m) => m.role === 'member');
    // 기존 제목 모으기
    const titles = new Set();
    for (let cursor = null; ;) {
      const r = await call('GET', `/api/boards/group/${g.id}/posts${cursor ? `?cursor=${cursor}` : ''}`, { admin: true });
      r.items.forEach((p) => titles.add(p.title));
      if (!r.nextCursor) break;
      cursor = r.nextCursor;
    }
    let ai = 0;
    for (const [cat, title, body, day, tier] of list) {
      n++;
      if (titles.has(title)) { stats.skipped++; continue; }
      if (!g.categories.includes(cat)) { console.warn(`분류 없음, 건너뜀: ${g.name} / ${cat}`); continue; }
      const pool = plain.length ? plain : mem;
      const author = cat === '공지' ? staff[n % staff.length] : (pool[(ai++ + n) % pool.length]);
      const res = await call('POST', `/api/boards/group/${g.id}/posts`, { as: author.userId, date: D(day), time: T(n), body: { category: cat, title, body } });
      stats.posts++;
      const t = TIER[tier];
      const others = mem.filter((m) => m.userId !== author.userId);
      // 댓글
      for (let i = 0; i < Math.min(t.c, others.length); i++) {
        const who = others[(i * 3 + n) % others.length];
        const d = Math.min(19, day + (i % 3 === 2 ? 1 : 0) + Math.floor(i / 4));
        await call('POST', `/api/posts/${res.id}/comments`, { as: who.userId, date: D(d), time: T(n + i), body: { body: C_GEN[(n * 5 + i * 7) % C_GEN.length] } });
        stats.comments++;
      }
      // 공감
      for (let i = 0; i < Math.min(t.l, others.length); i++) {
        await call('POST', `/api/posts/${res.id}/like`, { as: others[(i * 2 + n + 1) % others.length].userId, date: D(day), ok: [409] });
        stats.likes++;
      }
      // 조회 (여러 멤버가 기준일에 읽어요)
      for (let i = 0; i < t.v; i++) {
        await call('GET', `/api/posts/${res.id}`, { as: mem[(i + n) % mem.length].userId, date: TODAY });
        stats.views++;
      }
    }
    console.log(`${g.name}: 완료`);
  }
  console.log(`글 ${stats.posts}개 추가 (건너뜀 ${stats.skipped}) · 댓글 ${stats.comments} · 공감 ${stats.likes} · 조회 ${stats.views} · 요청 ${sent}건`);
}
main().catch((e) => { console.error(e.message); process.exit(1); });
